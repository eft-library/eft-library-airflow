import json

import pendulum


def v2_ammo_process(item_en, item_ko, item_ja):
    """
    ammo 데이터 가공
    """
    item_id = item_en.get("id")
    name = {
        "en": item_en.get("name"),
        "ko": item_ko.get("name"),
        "ja": item_ja.get("name"),
    }
    category = "Ammo"
    efficiency = get_efficiency(item_en.get("name"))
    image = item_en.get("gridImageLink")
    image_width = item_en.get("width")
    image_height = item_en.get("height")
    update_time = pendulum.now("Asia/Seoul")

    properties = item_en.get("properties") or {}
    damage = properties.get("damage")
    penetration_power = properties.get("penetrationPower")
    armor_damage = properties.get("armorDamage")
    accuracy_modifier = properties.get("accuracyModifier")
    recoil_modifier = properties.get("recoilModifier")
    light_bleed_modifier = properties.get("lightBleedModifier")
    heavy_bleed_modifier = properties.get("heavyBleedModifier")

    info = json.dumps(
        {
            "damage": damage,
            "efficiency": efficiency,
            "penetration_power": penetration_power,
            "armor_damage": armor_damage,
            "accuracy_modifier": accuracy_modifier,
            "recoil_modifier": recoil_modifier,
            "light_bleed_modifier": light_bleed_modifier,
            "heavy_bleed_modifier": heavy_bleed_modifier,
        }
    )

    return (
        item_id,
        json.dumps(name),
        category,
        info,
        image,
        image_width,
        image_height,
        update_time,
    )


